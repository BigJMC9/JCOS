#ifndef JCOS_GRAPHICS_SUPERVISOR_PROTOCOL_H
#define JCOS_GRAPHICS_SUPERVISOR_PROTOCOL_H
/* Private four-scalar supervisor exchange; no device addresses or grants. */
#define GRAPHICS_POLICY_VERSION (3ULL << 56)
#define GRAPHICS_POLICY_BEGIN 1U
#define GRAPHICS_POLICY_PRIMARY 2U
#define GRAPHICS_POLICY_OBSERVE 3U
#define GRAPHICS_POLICY_RESCUED 4U
#define GRAPHICS_POLICY_REQUEST_RESCUE 5U
#define GRAPHICS_POLICY_CLOSE 6U
#define GRAPHICS_POLICY_CLIENT_RECONNECT 7U
#define GRAPHICS_POLICY_RESTART_PRIMARY 8U
#define GRAPHICS_POLICY_PRIMARY_RESTARTED 9U
#define GRAPHICS_POLICY_PRIMARY_LIVE (1ULL << 8)
#define GRAPHICS_POLICY_RESCUE_LIVE (1ULL << 9)
#define GRAPHICS_POLICY_PRIMARY_PONG (1ULL << 10)
#define GRAPHICS_POLICY_RESCUE_PONG (1ULL << 11)
#define GRAPHICS_POLICY_PROBED (1ULL << 12)
#define GRAPHICS_POLICY_OBSERVE_FACTS (0x1FULL << 8)
#define GRAPHICS_POLICY_CLIENT_DRAINED (1ULL << 13)
#define GRAPHICS_POLICY_OUTPUT_CHANGED (1ULL << 14)
#define GRAPHICS_POLICY_RECONNECT_FACTS (GRAPHICS_POLICY_RESCUE_LIVE | GRAPHICS_POLICY_RESCUE_PONG | GRAPHICS_POLICY_PROBED | GRAPHICS_POLICY_CLIENT_DRAINED | GRAPHICS_POLICY_OUTPUT_CHANGED)
#define GRAPHICS_POLICY_BACKEND_READONLY (1ULL << 15)
#define GRAPHICS_POLICY_OUTPUT_STABLE (1ULL << 16)
#define GRAPHICS_POLICY_RESTART_FACTS (GRAPHICS_POLICY_OBSERVE_FACTS | GRAPHICS_POLICY_CLIENT_DRAINED | GRAPHICS_POLICY_BACKEND_READONLY | GRAPHICS_POLICY_OUTPUT_STABLE)
#define GRAPHICS_POLICY_FACTS (0x1FFULL << 8)
#define GRAPHICS_POLICY_ACCEPT 0ULL
#define GRAPHICS_POLICY_KEEP 1ULL
#define GRAPHICS_POLICY_RECOVER 2ULL
#define GRAPHICS_POLICY_HEADLESS 3ULL
#define GRAPHICS_POLICY_CONNECT 4ULL
#define GRAPHICS_POLICY_RESTART 5ULL
#define GRAPHICS_POLICY_REJECT 6ULL
#endif
